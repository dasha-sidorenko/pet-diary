  function pick(list, seed) {
    if (!list || !list.length) return "";
    const i = seed === undefined ? Math.floor(Math.random() * list.length) : seed % list.length;
    return list[i];
  }

  // Факт дня: меняется раз в сутки, чередуются факты про вид и общие
  function factsFor(species) {
    return (FACTS[species] || []).concat(FACTS.all);
  }

  function dayNumber() {
    const d = new Date();
    return Math.floor(new Date(d.getFullYear(), d.getMonth(), d.getDate()).getTime() / 86400000);
  }

  function fact(species, shift) {
    const list = factsFor(species);
    return list[(dayNumber() + (shift || 0)) % list.length];
  }

  // {мужской|женский} — форма слова по полу питомца
  function phrase(kind, pet, vars) {
    let text = pick(PHRASES[kind]);
    if (!text) return "";
    const female = pet && pet.sex === "f";
    text = text.replace(/\{([^|{}]*)\|([^|{}]*)\}/g, (m, a, b) => (female ? b : a));
    const species = pet ? pet.species : "other";
    Object.keys(vars || {}).forEach((k) => (text = text.replace("{" + k + "}", vars[k])));
    return (kind === "sleep" ? "" : VOICE[species] || "") + text;
  }

